export function fightText(def) {
  const atks = def.atk ? (Array.isArray(def.atk) ? def.atk : [def.atk]) : [];
  const lines = [];
  lines.push((MOVE_TEXT[def.move] || 'Moves') + '.');
  if (atks.length) lines.push('Attacks with ' + atks.map((a) => ATK_TEXT[a.type] || a.type).join(' and ') + '.');
  else if (def.move !== 'turret') lines.push('Attacks up close.');
  for (const t of Object.keys(def.traits || {})) if (TRAIT_TEXT[t]) lines.push(TRAIT_TEXT[t] + '.');
  return lines;
}
